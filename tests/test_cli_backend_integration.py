"""
Contract and schema integration tests between DevMemory CLI and Backend schemas.
Ensures that payloads generated by the CLI diagnostic engine strictly conform
to FastAPI / Pydantic schema validation expectations.
"""

import sys
import uuid
from pathlib import Path

# Ensure server module can be imported
server_dir = Path(__file__).resolve().parent.parent / "server"
if str(server_dir) not in sys.path:
    sys.path.insert(0, str(server_dir))

from devmemory.integration.models import (
    BackendEnvironmentInfo,
    BackendErrorContext,
    IncidentPayload,
)
from app.schemas.run import RunCreate, ErrorContext, EnvironmentInfo


def test_cli_payload_validates_against_backend_run_create_pydantic_schema():
    """Verify that an IncidentPayload serialized via to_dict() validates cleanly against backend RunCreate schema."""
    event_id = str(uuid.uuid4())
    project_id = str(uuid.uuid4())

    err_ctx = BackendErrorContext(
        error_type="ZeroDivisionError",
        message="float division by zero",
        file_path="src/math_ops.py",
        line=42,
        column=5,
        snippet="41:    return a\n42:    / b",
    )

    env_info = BackendEnvironmentInfo(
        os="Windows-11",
        runtime_version="3.13.5",
        git_branch="feat/integration-cli-backend",
    )

    payload = IncidentPayload(
        event_id=event_id,
        project_id=project_id,
        project_name="calc-service",
        command="python -m pytest tests/",
        cwd="C:/work/calc",
        started_at="2026-10-10T12:00:00Z",
        ended_at="2026-10-10T12:00:05Z",
        duration_ms=5000,
        exit_code=1,
        interrupted=False,
        stdout="collected 1 item\nFAILED tests/test_calc.py - ZeroDivisionError",
        stderr="Traceback (most recent call last): ...",
        error_context=err_ctx,
        environment=env_info,
    )

    data = payload.to_dict()

    # Pass dictionary directly into backend's Pydantic model
    run_create = RunCreate.model_validate(data)

    assert run_create.event_id == event_id
    assert run_create.project_id == project_id
    assert run_create.command == "python -m pytest tests/"
    assert run_create.duration_ms == 5000
    assert run_create.exit_code == 1
    assert run_create.error_context is not None
    assert run_create.error_context.error_type == "ZeroDivisionError"
    assert run_create.error_context.line == 42
    assert run_create.environment is not None
    assert run_create.environment.runtime_version == "3.13.5"
    assert run_create.environment.os == "Windows-11"


def test_cli_payload_without_error_context_validates_for_successful_runs():
    """Verify successful run without error_context validates cleanly against RunCreate."""
    payload = IncidentPayload(
        event_id=str(uuid.uuid4()),
        project_id=str(uuid.uuid4()),
        project_name="clean-run",
        command="python --version",
        cwd="C:/work",
        started_at="2026-10-10T12:00:00Z",
        ended_at="2026-10-10T12:00:00.100Z",
        duration_ms=100,
        exit_code=0,
        interrupted=False,
        stdout="Python 3.13.5",
        stderr="",
        error_context=None,
    )

    data = payload.to_dict()
    run_create = RunCreate.model_validate(data)

    assert run_create.command == "python --version"
    assert run_create.exit_code == 0
    assert run_create.error_context is None


def test_error_context_standalone_validation():
    """Verify BackendErrorContext converts cleanly into backend ErrorContext schema."""
    ctx = BackendErrorContext(
        error_type="SyntaxError",
        message="invalid syntax",
        file_path="main.py",
        line=10,
        column=12,
        snippet="print 'missing parentheses'",
    )
    validated = ErrorContext.model_validate(ctx.to_dict())
    assert validated.error_type == "SyntaxError"
    assert validated.message == "invalid syntax"
    assert validated.file_path == "main.py"
    assert validated.line == 10
    assert validated.column == 12
    assert validated.snippet == "print 'missing parentheses'"


def test_environment_info_standalone_validation():
    """Verify BackendEnvironmentInfo converts cleanly into backend EnvironmentInfo schema."""
    env = BackendEnvironmentInfo(
        os="Linux",
        runtime_version="Python 3.12.2",
        git_branch="main",
        git_commit="abcdef123456",
    )
    validated = EnvironmentInfo.model_validate(env.to_dict())
    assert validated.os == "Linux"
    assert validated.runtime_version == "Python 3.12.2"
    assert validated.git_branch == "main"
    assert validated.git_commit == "abcdef123456"

