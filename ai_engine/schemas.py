"""Shared Pydantic schemas and contracts for DevMemory AI & Memory Engine.

Defines stable contracts for diagnosis requests, diagnosis responses,
source locations, snippets, incident matches, knowledge-base entries,
and fix verification outcomes.
"""

from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field, model_validator


class MatchSource(str, Enum):
    """Source origin for a retrieved troubleshooting match."""
    GENERAL_KNOWLEDGE = "general_knowledge"
    PROJECT_MEMORY = "project_memory"
    CROSS_PROJECT = "cross_project"


class FixVerificationStatus(str, Enum):
    """Verification outcome of a proposed fix or past incident resolution."""
    VERIFIED = "verified"
    UNVERIFIED = "unverified"
    FAILED = "failed"


class FixStatus(str, Enum):
    """Status lifecycle of a fix in a diagnosis result.
    
    IMPORTANT: Generated recommendations start as UNVERIFIED or PROPOSED.
    They must never be marked VERIFIED without actual test/command verification.
    """
    PROPOSED = "proposed"
    UNVERIFIED = "unverified"
    VERIFIED = "verified"
    FAILED = "failed"


class SourceLocation(BaseModel):
    """Represents a specific code location identified in an error or stack trace."""
    model_config = ConfigDict(frozen=True, extra="forbid")

    file_path: str = Field(
        ...,
        min_length=1,
        max_length=1000,
        description="Path to the source file where the error occurred.",
    )
    line: int = Field(
        ...,
        gt=0,
        description="1-indexed line number in the source file.",
    )
    column: Optional[int] = Field(
        default=None,
        gt=0,
        description="Optional 1-indexed column number.",
    )
    function_name: Optional[str] = Field(
        default=None,
        max_length=256,
        description="Enclosing function or method name, if identifiable.",
    )


class SourceSnippet(BaseModel):
    """Enclosing source code context around an error location."""
    model_config = ConfigDict(frozen=True, extra="forbid")

    file_path: str = Field(
        ...,
        min_length=1,
        max_length=1000,
        description="Path to the source file.",
    )
    start_line: int = Field(
        ...,
        gt=0,
        description="1-indexed start line of the snippet.",
    )
    end_line: int = Field(
        ...,
        gt=0,
        description="1-indexed end line of the snippet.",
    )
    content: str = Field(
        ...,
        max_length=20000,
        description="Source code snippet content.",
    )

    @model_validator(mode="after")
    def validate_line_range(self) -> "SourceSnippet":
        if self.end_line < self.start_line:
            raise ValueError(
                f"end_line ({self.end_line}) cannot be earlier than start_line ({self.start_line})"
            )
        return self


class IncidentMatch(BaseModel):
    """Historical incident or general knowledge match retrieved for an error."""
    model_config = ConfigDict(extra="forbid")

    incident_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Identifier of the historical incident or knowledge entry.",
    )
    project_id: Optional[str] = Field(
        default=None,
        max_length=128,
        description="Project identifier, provided only when disclosure policy permits.",
    )
    match_source: MatchSource = Field(
        ...,
        description="Memory level: general_knowledge, project_memory, or cross_project.",
    )
    similarity_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Heuristic similarity/relevance score between 0.0 and 1.0.",
    )
    explanation: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Explanation of why this candidate is relevant and how it compares.",
    )
    resolution_summary: Optional[str] = Field(
        default=None,
        max_length=5000,
        description="Summary of resolution if available; sanitized for cross-project items.",
    )
    verification_status: FixVerificationStatus = Field(
        default=FixVerificationStatus.UNVERIFIED,
        description="Explicit verification status. Never inferred as verified without proof.",
    )


class DiagnosisRequest(BaseModel):
    """Input payload submitted to the AI Diagnosis & Memory Engine."""
    model_config = ConfigDict(extra="forbid")

    event_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Unique event UUID generated by the runner.",
    )
    project_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Identifier of the originating project.",
    )
    command: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Developer command that was executed.",
    )
    exit_code: int = Field(
        ...,
        description="Process exit code (e.g. non-zero for failed commands).",
    )
    error_message: str = Field(
        ...,
        min_length=1,
        max_length=10000,
        description="Extracted primary error message.",
    )
    stack_trace: Optional[str] = Field(
        default=None,
        max_length=50000,
        description="Captured stack trace text, if available.",
    )
    locations: List[SourceLocation] = Field(
        default_factory=list,
        max_length=50,
        description="Parsed source code locations where error occurred.",
    )
    source_snippets: List[SourceSnippet] = Field(
        default_factory=list,
        max_length=20,
        description="Enclosing source code snippets associated with locations.",
    )
    allow_cross_project: bool = Field(
        default=False,
        description="Client preference flag. Actual sharing policy is enforced server-side.",
    )


class DiagnosisResponse(BaseModel):
    """Structured response returned by the AI Diagnosis & Memory Engine."""
    model_config = ConfigDict(extra="forbid")

    event_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Unique event UUID matching the originating request.",
    )
    summary: str = Field(
        ...,
        min_length=1,
        max_length=1000,
        description="Concise human-readable summary of the error.",
    )
    likely_cause: str = Field(
        ...,
        min_length=1,
        max_length=5000,
        description="Analysis of the most probable cause based on evidence.",
    )
    evidence: List[str] = Field(
        default_factory=list,
        max_length=100,
        description="Concrete observed facts (error messages, code lines, exit codes).",
    )
    hypotheses: List[str] = Field(
        default_factory=list,
        max_length=50,
        description="Inferred hypotheses clearly distinguished from observed evidence.",
    )
    recommended_steps: List[str] = Field(
        default_factory=list,
        max_length=50,
        description="Concrete, actionable troubleshooting steps.",
    )
    related_incidents: List[IncidentMatch] = Field(
        default_factory=list,
        max_length=20,
        description="Relevant historical matches from the 3-level memory system.",
    )
    uncertainty_description: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Explicit description of assumptions, missing context, or uncertainties.",
    )
    confidence: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Heuristic confidence score (0.0 - 1.0). Does not imply mathematical certainty.",
    )
    verification_steps: List[str] = Field(
        default_factory=list,
        max_length=50,
        description="Specific tests or commands to verify whether the fix resolved the error.",
    )
    fix_status: FixStatus = Field(
        default=FixStatus.UNVERIFIED,
        description="Explicit fix status. Newly generated recommendations default to unverified.",
    )


class KnowledgeBaseItem(BaseModel):
    """Preloaded curated general programming error knowledge entry."""
    model_config = ConfigDict(extra="forbid")

    kb_id: str = Field(..., min_length=1, max_length=128)
    error_pattern: str = Field(..., min_length=1, max_length=1000)
    language: str = Field(default="general", max_length=64)
    title: str = Field(..., min_length=1, max_length=256)
    explanation: str = Field(..., min_length=1, max_length=5000)
    possible_causes: List[str] = Field(default_factory=list, max_length=20)
    diagnostic_checks: List[str] = Field(default_factory=list, max_length=20)
    suggested_resolutions: List[str] = Field(default_factory=list, max_length=20)
    tags: List[str] = Field(default_factory=list, max_length=20)


class FixOutcome(BaseModel):
    """Recorded outcome of a verification attempt for a proposed fix."""
    model_config = ConfigDict(extra="forbid")

    outcome_id: str = Field(..., min_length=1, max_length=128)
    incident_id: str = Field(..., min_length=1, max_length=128)
    project_id: str = Field(..., min_length=1, max_length=128)
    verification_status: FixVerificationStatus = Field(...)
    verification_command: Optional[str] = Field(default=None, max_length=2000)
    verification_output: Optional[str] = Field(default=None, max_length=50000)
    recurred: Optional[bool] = None
    notes: Optional[str] = Field(default=None, max_length=2000)
